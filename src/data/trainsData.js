// Pre-process trains to populate default stops if missing
const PROCESSED_TRAINS = TRAINS_DATA.map(t => {
  let stops = t.stops ? [...t.stops] : [];
  if (stops.length === 0 && t.subLine && SUBURBAN_ROUTE_MAP[t.subLine]) {
    stops = SUBURBAN_ROUTE_MAP[t.subLine];
  } else if (stops.length === 0) {
    stops = [t.origin, t.destination];
  }
  return { ...t, stops };
});

// Helper to query trains
export function searchTrains({ from, to, date, category }) {
  const cleanFrom = (from || '').toLowerCase().trim();
  const cleanTo = (to || '').toLowerCase().trim();

  return PROCESSED_TRAINS.filter(t => {
    // Check Category filter
    if (category && category !== 'all') {
      const catLower = (t.category || '').toLowerCase();
      if (!catLower.includes(category.toLowerCase())) return false;
    }

    if (!cleanFrom && !cleanTo) return true;

    const origLower = (t.origin || '').toLowerCase();
    const destLower = (t.destination || '').toLowerCase();
    const stopsLower = (t.stops || []).map(s => s.toLowerCase());
    const nameLower = (t.name || '').toLowerCase();
    const numLower = (t.number || '').toLowerCase();
    const subLower = (t.subLine || '').toLowerCase();

    const matchesFrom = !cleanFrom ||
      origLower.includes(cleanFrom) ||
      stopsLower.some(s => s.includes(cleanFrom)) ||
      nameLower.includes(cleanFrom) ||
      numLower.includes(cleanFrom) ||
      subLower.includes(cleanFrom);

    const matchesTo = !cleanTo ||
      destLower.includes(cleanTo) ||
      stopsLower.some(s => s.includes(cleanTo)) ||
      nameLower.includes(cleanTo) ||
      numLower.includes(cleanTo) ||
      subLower.includes(cleanTo);

    return matchesFrom && matchesTo;
  });
}
